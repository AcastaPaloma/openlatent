"""H4 strong attacker (H.md 9.1): transformer over bags of 16 consecutive windows with a residual 1-D CNN / MLP window encoder, augmentation, 3,000 steps.
  python strong_attack.py --arm predlabel --rungs 0.25,0.5,1.0 --folds S0,S1,S2 --out DIR [--rel_file NPZ] [--shuffle] [--steps 3000]
Sealed MotionSense set, releases exactly as in arm B (code floors regenerated by the frozen suite.build_release; aae_re releases read from the arm-B files).
Writes strong__<arm>__p<rung>.npz (per trial: sub, correct) and strong__<arm>.json (aggregates)."""
import os, sys, json, time, argparse, math, zlib
import numpy as np
import torch
from torch import nn
sys.path.insert(0, os.path.dirname(__file__))
import common as C
import datasets as D
import suite as SU

T = 16; BS = 128; NID = 24


class Block(nn.Module):
    def __init__(s, cin, cout, stride):
        super().__init__()
        s.c1 = nn.Conv1d(cin, cout, 5, stride, 2, bias=False); s.b1 = nn.BatchNorm1d(cout)
        s.c2 = nn.Conv1d(cout, cout, 5, 1, 2, bias=False); s.b2 = nn.BatchNorm1d(cout)
        s.sk = nn.Sequential(nn.Conv1d(cin, cout, 1, stride, bias=False), nn.BatchNorm1d(cout)) if (cin != cout or stride != 1) else nn.Identity()
        s.act = nn.GELU()

    def forward(s, x):
        o = s.act(s.b1(s.c1(x))); o = s.b2(s.c2(o)); return s.act(o + s.sk(x))


class WinEnc(nn.Module):
    def __init__(s):
        super().__init__()
        s.stem = nn.Sequential(nn.Conv1d(2, 64, 7, 1, 3, bias=False), nn.BatchNorm1d(64), nn.GELU())
        s.body = nn.Sequential(Block(64, 64, 1), Block(64, 64, 1), Block(64, 128, 2), Block(128, 128, 1), Block(128, 256, 2), Block(256, 256, 1))
        s.fc = nn.Linear(512, 128)

    def forward(s, x):  # (N,2,128)
        h = s.body(s.stem(x)); return s.fc(torch.cat([h.mean(2), h.amax(2)], 1))


class CodeEnc(nn.Module):
    def __init__(s, d):
        super().__init__()
        s.net = nn.Sequential(nn.Linear(d, 256), nn.GELU(), nn.Linear(256, 256), nn.GELU(), nn.Linear(256, 128), nn.LayerNorm(128), nn.Dropout(0.1))

    def forward(s, x): return s.net(x)


class SeqNet(nn.Module):
    def __init__(s, kind, d_in):
        super().__init__()
        s.enc = WinEnc() if kind == "win" else CodeEnc(d_in)
        s.pos = nn.Parameter(torch.zeros(1, T, 128))
        s.tf = nn.TransformerEncoder(nn.TransformerEncoderLayer(128, 4, 256, 0.1, batch_first=True, norm_first=True), 2)
        s.out = nn.Linear(128, NID)

    def forward(s, x):  # (B,T,...)
        B = x.shape[0]; h = s.enc(x.reshape(B * T, *x.shape[2:])).reshape(B, T, 128)
        return s.out(s.tf(h + s.pos).mean(1))


def augment(x, kind):
    """x (B,T,...) float; window releases: scale / noise / shift / time mask; code releases: jitter / feature dropout"""
    if kind == "win":
        B = x.shape[0]
        x = x * (0.85 + 0.3 * torch.rand(B, T, 2, 1, device=x.device)) + 0.05 * torch.randn_like(x)
        sh = int(torch.randint(-8, 9, (1,)))
        x = torch.roll(x, sh, dims=-1)
        m = (torch.rand(B, T, 1, 1, device=x.device) < 0.3)
        st = torch.randint(0, 112, (B, T, 1, 1), device=x.device); ar = torch.arange(128, device=x.device).view(1, 1, 1, 128)
        mask = m & (ar >= st) & (ar < st + 16)
        return x.masked_fill(mask, 0.0)
    x = x + 0.05 * torch.randn_like(x)
    if x.shape[-1] >= 8:
        x = x * (torch.rand_like(x) > 0.05).float()
    return x


def run_arm(arm, rungs, folds, out, rel_file, shuffle, steps, seed, dev):
    t0 = time.time(); os.makedirs(out, exist_ok=True)
    S = D.get_set("sealed"); N = len(S["X"]); PHI = C.phi(S["X"]); sub = S["sub"]; tk = C.trial_key(S)
    shuffle = shuffle or arm == "shuf_raw"
    # trial segmentation (rows are contiguous per trial)
    ut, first, cnt = np.unique(tk, return_index=True, return_counts=True)
    for u, a_, c_ in zip(ut, first, cnt): assert (tk[a_:a_ + c_] == u).all(), "trial rows must be contiguous"
    summary = dict(arm=arm, steps=steps, seed=seed, shuffle=shuffle, rungs={})
    for p in rungs:
        pk = f"p{p}"; per = dict(corr=np.zeros(NID), n=np.zeros(NID), seg_corr=0.0, seg_n=0.0, folds={})
        pack = {}
        for f in folds:
            te = D.test_mask(S, f); tr_fs = (~te) & S["is_train_window"]
            if arm in ("raw", "shuf_raw"): R, kind = S["X"], "win"
            elif arm in ("aae_re", "aae_re_c2s0"): R, kind = np.load(rel_file)[f"release_{f}"].astype(np.float32), "win"
            elif arm == "ctrl_const": R, kind = np.zeros((N, 1), np.float32), "code"
            else: R, kind = SU.build_release(arm, S, PHI, tr_fs, f, None)
            tr_rows = ~te
            if kind == "win":
                mu = R[tr_rows].mean((0, 2), keepdims=True); sd = R[tr_rows].std((0, 2), keepdims=True) + 1e-6
            else:
                mu = R[tr_rows].mean(0, keepdims=True); sd = R[tr_rows].std(0, keepdims=True) + 1e-6
            Rg = torch.from_numpy(((R - mu) / sd).astype(np.float32)).to(dev)
            # training trials (prefix of fraction p) and test trials
            trials = []
            for u, a, c in zip(ut, first, cnt):
                rows = np.arange(a, a + c)
                if te[a]: continue
                n_p = max(1, int(math.ceil(p * c))); trials.append((a, n_p, int(sub[a])))
            rr = np.random.default_rng(99).permutation(NID)
            lab_map = (lambda s_: int(rr[s_])) if shuffle else (lambda s_: s_)
            tr_start = torch.tensor([t[0] for t in trials], device=dev); tr_len = torch.tensor([t[1] for t in trials], device=dev)
            tr_lab = torch.tensor([lab_map(t[2]) for t in trials], device=dev)
            torch.manual_seed(seed * 1000 + zlib.crc32(f.encode()) % 997); np.random.seed(seed)
            net = SeqNet(kind, Rg.shape[-1] if kind == "code" else 0).to(dev)
            opt = torch.optim.AdamW(net.parameters(), lr=1e-3, weight_decay=0.05)
            sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, steps)
            ls = nn.CrossEntropyLoss(label_smoothing=0.1)
            net.train()
            for it in range(steps):
                ti = torch.randint(0, len(trials), (BS,), device=dev)
                off = (torch.rand(BS, device=dev) * (tr_len[ti] - T + 1).clamp(min=1).float()).long()
                idx = tr_start[ti].unsqueeze(1) + (off.unsqueeze(1) + torch.arange(T, device=dev).unsqueeze(0)) % tr_len[ti].unsqueeze(1)  # cyclic padding when a trial (prefix) has fewer than T windows
                x = augment(Rg[idx], kind)
                with torch.autocast(device_type=dev.type, dtype=torch.bfloat16, enabled=(dev.type == "cuda")):
                    loss = ls(net(x), tr_lab[ti])
                opt.zero_grad(set_to_none=True); loss.backward(); nn.utils.clip_grad_norm_(net.parameters(), 1.0); opt.step(); sched.step()
            net.eval()
            fc, fn, sc, sn = np.zeros(NID), np.zeros(NID), 0.0, 0.0
            tkeys, preds, subs = [], [], []
            with torch.no_grad():
                for u, a, c in zip(ut, first, cnt):
                    if not te[a]: continue
                    starts = torch.arange(0, max(int(c) - T, 0) + 1, 4, device=dev)
                    idx = a + (starts.unsqueeze(1) + torch.arange(T, device=dev).unsqueeze(0)) % int(c)  # cyclic padding for trials with fewer than T windows
                    with torch.autocast(device_type=dev.type, dtype=torch.bfloat16, enabled=(dev.type == "cuda")):
                        lg = net(Rg[idx]).float()
                    lp = torch.log_softmax(lg, -1); s_true = int(sub[a])
                    pred = int(lp.mean(0).argmax()); ok = float(pred == s_true)
                    fc[s_true] += ok; fn[s_true] += 1; sc += float((lg.argmax(1) == s_true).sum()); sn += len(starts)
                    tkeys.append(int(u)); preds.append(pred); subs.append(s_true)
            per["corr"] += fc; per["n"] += fn; per["seg_corr"] += sc; per["seg_n"] += sn
            per["folds"][f] = dict(trials=int(fn.sum()), trial_acc=float(fc.sum() / max(fn.sum(), 1)), seg_acc=float(sc / max(sn, 1)), seconds=round(time.time() - t0, 1))
            pack[f"{f}_tkey"] = np.array(tkeys); pack[f"{f}_pred"] = np.array(preds); pack[f"{f}_sub"] = np.array(subs)
            print(f"[{time.time()-t0:.0f}s] {arm} p={p} fold {f}: trial acc {per['folds'][f]['trial_acc']:.3f} seg acc {per['folds'][f]['seg_acc']:.3f}", flush=True)
        np.savez_compressed(os.path.join(out, f"strong__{arm}__{pk}.npz"), corr=per["corr"], n=per["n"], **pack)
        summary["rungs"][pk] = dict(L=float(per["corr"].sum() / per["n"].sum()), seg_acc=float(per["seg_corr"] / max(per["seg_n"], 1)), n_trials=int(per["n"].sum()), per_subject_corr=per["corr"].tolist(), per_subject_n=per["n"].tolist(), folds=per["folds"])
    summary["seconds"] = round(time.time() - t0, 1)
    json.dump(summary, open(os.path.join(out, f"strong__{arm}.json"), "w"), indent=1)
    print(json.dumps({k: (v["L"], v["seg_acc"]) for k, v in summary["rungs"].items()}))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--arm", required=True); ap.add_argument("--rungs", default="0.25,0.5,1.0"); ap.add_argument("--folds", default="S0,S1,S2")
    ap.add_argument("--out", required=True); ap.add_argument("--rel_file", default=None); ap.add_argument("--shuffle", action="store_true"); ap.add_argument("--steps", type=int, default=3000)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    torch.set_num_threads(8)
    dev = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
    run_arm(a.arm, [float(x) for x in a.rungs.split(",")], a.folds.split(","), a.out, a.rel_file, a.shuffle, a.steps, a.seed, dev)
