"""Results table from results/runs/*/result.json.

Strong = fresh models trained on anonymised data (privacy = best attacker). Weak = models trained
on raw data, tested on anonymised data. The main score is the gap between action accuracy and
strong privacy accuracy, with chance at 16.7 (action) and 4.0 (person).

Usage: python3 summarize.py <runs_dir> <out.md>
"""

import glob
import json
import os
import sys


def main(runs, out):
    rows = []
    for p in sorted(glob.glob(os.path.join(runs, "*", "result.json"))):
        r = json.load(open(p))
        if r["name"].startswith("smoke"):
            continue
        s, w = r["strong"], r.get("weak", {})
        rows.append(dict(
            name=r["name"], anon=json.dumps(r["config"]["anonymizer"]).replace('"', ""),
            split=r.get("split", "?"), dataset=r.get("dataset", "kth"), metric=r.get("privacy_metric", "top1"),
            act=r["action_top1"], priv=r.get("privacy_main", r.get("privacy_top1")),
            priv_f=s.get("person/frame_r50", s.get("attr/frame_r50")), priv_v=s.get("person/r3d", s.get("attr/r3d")),
            w_act=w.get("action/r2p1d"), w_priv=max([v for k, v in w.items() if not k.startswith("action/")], default=None),
            mins=r.get("minutes", 0)))
    # leakage = (privacy - floor) / (raw privacy - floor): 100% = as leaky as raw video, 0% = blind.
    # floor: identity chance (1/25) on KTH; on VP-UCF101 a constant predictor's cMAP = mean prevalence.
    raw, floor = {}, {"kth": 4.0}
    for p in glob.glob(os.path.join(runs, "*", "result.json")):
        r = json.load(open(p))
        ds = r.get("dataset", "kth")
        if r["config"]["anonymizer"]["type"] == "raw" and r.get("split", "ilic") in ("ilic", "s1"):
            raw[ds] = r.get("privacy_main", r.get("privacy_top1"))
            prev = [d.get("prevalence") for d in r.get("details", {}).values() if d.get("prevalence")]
            if prev:
                floor[ds] = sum(prev[0]) / len(prev[0])
    for d in rows:
        ds = d["dataset"]
        d["leak"] = (100 * (d["priv"] - floor[ds]) / (raw[ds] - floor[ds])) if ds in raw and ds in floor else None
    fmt = lambda v: "-" if v is None else f"{v:.1f}"  # noqa: E731
    rows.sort(key=lambda d: (d["dataset"], -((d["act"] or 0) - d["priv"])))
    lines = ["# Results (auto-generated by scripts/summarize.py)", "",
             "KTH privacy = actor identity top-1 (chance 4.0). VP-UCF101 privacy = cMAP over 5 attributes",
             "(lower is better; a blind predictor scores the attribute prevalence).", "",
             "Strong = action/identity models trained from scratch (pretrained init) on the anonymised",
             "data; privacy is the best of the identity attackers (frame ResNet-50, R3D-18 video).",
             "Weak = raw-trained models tested on anonymised data (Ilic et al. protocol).",
             "Chance: action 16.7, identity 4.0. Sorted by action - privacy (strong).", "",
             "Leakage = (privacy - floor) / (raw - floor): 100% as leaky as raw, 0% as a blind guess",
             "(floor: KTH 4.0 = chance; VP-UCF101 58.7 = cMAP of a constant predictor).", "",
             "| run | dataset | anonymizer | split | action (strong) | privacy (strong, best) | leakage | privacy frame / video | action (weak) | privacy (weak) | min |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in rows:
        lines.append(f"| {d['name']} | {d['dataset']} | `{d['anon']}` | {d['split']} | {fmt(d['act'])} | **{fmt(d['priv'])}** | {fmt(d['leak'])}% | "
                     f"{fmt(d['priv_f'])} / {fmt(d['priv_v'])} | {fmt(d['w_act'])} | {fmt(d['w_priv'])} | {d['mins']:.0f} |")
    text = "\n".join(lines) + "\n"
    open(out, "w").write(text)
    print(text)


if __name__ == "__main__":
    main(*sys.argv[1:3])
