import glob
import json
import os
import statistics as st

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
R = {}
for p in glob.glob(os.path.join(ROOT, "results", "runs", "*", "result.json")):
    d = json.load(open(p))
    R[d["name"]] = d


def pv(d):
    return d.get("privacy_main", d.get("privacy_top1"))


def fmt(v):
    return f"{st.mean(v):.1f}" + (f" ± {st.pstdev(v):.1f}" if len(v) > 1 else "")


def agg(names):
    xs = [R[n] for n in names if n in R]
    if not xs:
        return None
    a = [x["action_top1"] for x in xs if x.get("action_top1") is not None]
    return (fmt(a) if a else "–"), fmt([pv(x) for x in xs]), len(xs)


def cross(names):
    xs = [pv(R[n]) for n in names if n in R]
    return fmt(xs) if xs else "–"


